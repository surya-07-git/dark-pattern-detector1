"""
Exports the Scikit-Learn TF-IDF + LinearSVC Pipeline to a compact JSON and
Browser-ready JavaScript module for 100% local, zero-dependency in-extension inference.
"""

import os
import json
import joblib
import numpy as np

def export():
    model_path = os.path.join(os.path.dirname(__file__), "model.joblib")
    if not os.path.exists(model_path):
        print("[-] model.joblib not found. Run train_model.py first.")
        return

    pipeline = joblib.load(model_path)
    tfidf = pipeline.named_steps['tfidf']
    clf = pipeline.named_steps['clf']

    # Extract vocabulary dictionary: { term: feature_index }
    vocab = tfidf.vocabulary_
    idf = tfidf.idf_.tolist()
    classes = clf.classes_.tolist()
    coef = clf.coef_.tolist() # shape: (n_classes, n_features)
    intercept = clf.intercept_.tolist() # shape: (n_classes,)

    payload = {
        "version": "1.0.0",
        "algorithm": "TF-IDF + LinearSVC",
        "classes": classes,
        "vocabulary": {k: int(v) for k, v in vocab.items()},
        "idf": [round(float(v), 5) for v in idf],
        "coef": [[round(float(v), 5) for v in row] for row in coef],
        "intercept": [round(float(v), 5) for v in intercept],
        "ngram_range": [1, 2],
        "sublinear_tf": True
    }

    # 1. Save JSON
    json_path = os.path.join(os.path.dirname(__file__), "exported_model.json")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(payload, f, separators=(',', ':'))
    print(f"[+] Saved model JSON to: {json_path} ({os.path.getsize(json_path) / 1024:.1f} KB)")

    # 2. Save JavaScript bundle for Chrome Extension
    js_dest = os.path.join(r"c:\mini project\extension\content\model_weights.js")
    os.makedirs(os.path.dirname(js_dest), exist_ok=True)
    
    serialized_data = json.dumps(payload, separators=(',', ':'))
    js_content = """/**
 * Autogenerated Model Weights & Vocabulary for In-Browser Local ML Inference
 * Generated from Scikit-Learn TF-IDF + LinearSVC Pipeline.
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.DarkPatternModelWeights = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  return """ + serialized_data + """;
}));
"""
    with open(js_dest, "w", encoding="utf-8") as f:
        f.write(js_content)
    print(f"[+] Saved browser JS weights to: {js_dest} ({os.path.getsize(js_dest) / 1024:.1f} KB)")

if __name__ == "__main__":
    export()
